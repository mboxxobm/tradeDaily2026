#!/usr/bin/env python3
"""Regenerate GoldRetailBias.pine from GOLD_retail_daily.csv.
Usage: python make_pine.py [csv_path_or_url] [out.pine]
Default csv: ../GOLD_retail_daily.csv (repo layout), falls back to GitHub raw URL."""
import csv, io, os, sys, urllib.request
from datetime import date

RAW = "https://raw.githubusercontent.com/mboxxobm/tradeDaily2026/main/GOLDandForex/GOLD_retail_daily.csv"
here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "GOLD_retail_daily.csv")
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "GoldRetailBias.pine")
if src.startswith("http") or not os.path.exists(src):
    text = urllib.request.urlopen(src if src.startswith("http") else RAW).read().decode("utf-8")
else:
    text = open(src, encoding="utf-8").read()
rows = {}
for r in csv.DictReader(io.StringIO(text)):
    if not r.get("long_pct"): continue
    d = date.fromisoformat(r["date_utc"])
    rows[d] = float(r["long_pct"])
items = sorted(rows.items())
base = items[0][0]
days = ",".join(str((d - base).days) for d, _ in items)          # day offsets from base
vals = ",".join(("%g" % v) for _, v in items)
last = items[-1][0].isoformat()

pine = f'''//@version=6
// GoldRetailBias - forexsentiment.live XAUUSD retail Long% (daily). Generated by make_pine.py
// Data: {items[0][0].isoformat()} .. {last} ({len(items)} rows). Refresh: rerun make_pine.py and re-paste.
// (Pine Seeds / request.seed is NOT used; data is embedded.)
indicator("Gold Retail Bias (Long%)", shorttitle="GoldRetailBias", overlay=false, max_bars_back=5000)

hiLvl  = input.float(70, "Upper level")
midLvl = input.float(50, "Mid level")
loLvl  = input.float(30, "Lower level")
showBg = input.bool(true, "Background when beyond levels")

const int BASE_Y = {base.year}
const int BASE_M = {base.month}
const int BASE_D = {base.day}
const string DAYS = "{days}"
const string VALS = "{vals}"

var array<int>   dts  = array.new<int>()
var array<float> lng  = array.new<float>()
var int ptr = -1

if barstate.isfirst
    baseTs = timestamp("UTC", BASE_Y, BASE_M, BASE_D, 0, 0)
    ds = str.split(DAYS, ",")
    vs = str.split(VALS, ",")
    for i = 0 to array.size(ds) - 1
        array.push(dts, baseTs + int(str.tonumber(array.get(ds, i))) * 86400000)
        array.push(lng, str.tonumber(array.get(vs, i)))

// UTC date of this bar
barDay = timestamp("UTC", year(time, "UTC"), month(time, "UTC"), dayofmonth(time, "UTC"), 0, 0)
n = array.size(dts)
while ptr + 1 < n and array.get(dts, ptr + 1) <= barDay
    ptr += 1
float longPct = ptr >= 0 ? array.get(lng, ptr) : na

plot(longPct, "Long%", color=color.new(color.blue, 0), linewidth=2, style=plot.style_stepline)
hline(hiLvl,  "Upper", color=color.red,   linestyle=hline.style_dashed)
hline(midLvl, "Mid",   color=color.gray,  linestyle=hline.style_dotted)
hline(loLvl,  "Lower", color=color.green, linestyle=hline.style_dashed)
bgcolor(showBg and longPct > hiLvl ? color.new(color.red, 85) : showBg and longPct < loLvl ? color.new(color.green, 85) : na)
alertcondition(ta.crossover(longPct, hiLvl),  "Long% cross above upper", "Gold retail Long% crossed above upper level")
alertcondition(ta.crossunder(longPct, loLvl), "Long% cross below lower", "Gold retail Long% crossed below lower level")
'''
open(out, "w", encoding="utf-8").write(pine)
print(f"wrote {out}: {len(items)} rows, last {last}")
